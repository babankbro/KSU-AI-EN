/* Generate src/ksecData.js from the vault codebook so the app can never drift from the document.
   Source: Labor_Growth_Report_Vault/05_TQF2_Academic_Drafts/18_KSEC_Codebook.md (KSEC)
   Run:    npm run build:ksa                                                            */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const SRC = path.join(root, "Labor_Growth_Report_Vault/05_TQF2_Academic_Drafts/18_KSEC_Codebook.md");
const OUT = path.join(root, "curriculum-graph/src/ksecData.js");

/* วอลต์บน Windows อาจถูกบันทึกเป็น CRLF — ปรับให้เป็น LF ก่อน ไม่งั้น regex ที่ปิดท้ายด้วย $ จะไม่ตรง */
const md = fs.readFileSync(SRC, "utf8").replaceAll("\r\n", "\n");
const between = (a, b) => md.split(a)[1].split(b)[0];

const CODE = /\b(?:HS|SS|EF)\d{1,2}\b/g;
function expand(text) {
  const out = new Set(text.match(CODE) || []);
  for (const m of text.matchAll(/\b(HS|SS|EF)(\d{1,2})\s*[–-]\s*(?:HS|SS|EF)?(\d{1,2})\b/g))
    for (let i = +m[2]; i <= +m[3]; i++) out.add(m[1] + i);
  return [...out];
}
const aiskOf = t => [...new Set(t.match(/AISK\d{2}/g) || [])];
const ploOf = t => [...new Set([...t.matchAll(/PLO(\d)/g)].map(m => +m[1]))].sort();

const K = [], S = [], E = [], C = [];

/* ── Knowledge: | **K1** | name | scope | skills | AISK | PLO | ── */
for (const m of between("# ส่วน 1", "# ส่วน 2").matchAll(/^\|\s*\*\*(K\d+)\*\*\s*\|(.+)\|\s*$/gm)) {
  const c = m[2].split("|").map(x => x.trim());
  K.push({ id: m[1], name: c[0], scope: c[1] || "", skills: expand(c[2] || ""), aisk: aiskOf(c[3] || ""), plo: ploOf(c[4] || "") });
}

/* ── Skill: callout cards with a "ทำอะไรได้บ้าง" bullet list ── */
for (const card of between("# ส่วน 2", "# ส่วน 3").split(/^> \[!abstract\]- /m).slice(1)) {
  const head = card.split("\n")[0];
  const h = head.match(/\*\*(S\d+)\s*·\s*(.+?)\*\*\s*—\s*(.+)/);
  if (!h) continue;
  const metaLine = card.split("\n").find(l => l.startsWith("> **🔗 AISK**")) || "";
  S.push({
    id: h[1], name: h[2].trim(),
    can: card.split("\n").filter(l => /^>\s*-\s/.test(l)).map(l => l.replace(/^>\s*-\s*/, "").trim()),
    skills: expand(h[3]),
    type: /Soft/.test(h[3]) ? "Soft" : /ฐานวิศวกรรม/.test(h[3]) ? "ฐานวิศวกรรม" : "Hard",
    level: (h[3].match(/·\s*(B[1-6](?:–B[1-6])?)/) || [, ""])[1],
    aisk: aiskOf(metaLine), plo: ploOf(metaLine)
  });
}

/* ── Ethics / Character: | **E1** | name | covers | skills | PLO | evidence | เดิม | ── */
function readBehaviour(section, prefix, sink) {
  for (const m of section.matchAll(new RegExp(`^\\|\\s*\\*\\*(${prefix}\\d+)\\*\\*\\s*\\|(.+)\\|\\s*$`, "gm"))) {
    const c = m[2].split("|").map(x => x.trim());
    sink.push({ id: m[1], name: c[0], covers: c[1] || "", skills: expand(c[2] || ""), plo: ploOf(c[3] || ""), evidence: c[4] || "", legacy: c[5] || "" });
  }
}
readBehaviour(between("# ส่วน 3", "# ส่วน 4"), "E", E);
readBehaviour(between("# ส่วน 4", "# ส่วน 5"), "C", C);

/* ── reverse: skill -> KSA ── */
const rev = {};
for (const r of [...K, ...S, ...E, ...C])
  for (const sk of r.skills) (rev[sk] ||= { K: [], S: [], E: [], C: [] })[r.id[0]].push(r.id);
const num = a => +a.slice(1);
for (const sk of Object.keys(rev))
  for (const kind of ["K", "S", "E", "C"]) rev[sk][kind] = [...new Set(rev[sk][kind])].sort((a, b) => num(a) - num(b));

if (!K.length || !S.length || !E.length || !C.length) throw new Error("codebook parse produced an empty set — aborting");

const banner = `/* AUTO-GENERATED by scripts/build-ksec-data.mjs — do not edit by hand.
   Source of truth: Labor_Growth_Report_Vault/05_TQF2_Academic_Drafts/18_KSEC_Codebook.md
   Regenerate with: npm run build:ksa
   K${K.length} · S${S.length} · E${E.length} · C${C.length} */\n\n`;
fs.writeFileSync(OUT,
  banner +
  `export const KNOWLEDGE = ${JSON.stringify(K, null, 1)};\n\n` +
  `export const SKILLS_KSEC = ${JSON.stringify(S, null, 1)};\n\n` +
  `export const ETHICS = ${JSON.stringify(E, null, 1)};\n\n` +
  `export const CHARACTER = ${JSON.stringify(C, null, 1)};\n\n` +
  `/* รวมสองมิติเชิงพฤติกรรมไว้ให้หน้าที่ยังอ่านเป็นก้อนเดียว */\n` +
  `export const BEHAVIOUR = [...ETHICS, ...CHARACTER];\n\n` +
  `export const SKILL_TO_KSEC = ${JSON.stringify(rev, null, 1)};\n\n` +
  `export const KSEC_BY_ID = Object.fromEntries([...KNOWLEDGE, ...SKILLS_KSEC, ...ETHICS, ...CHARACTER].map(r => [r.id, r]));\n`,
  "utf8");

console.log(`ksecData.js: K=${K.length} S=${S.length} E=${E.length} C=${C.length} · skills mapped=${Object.keys(rev).length}`);
const missing = [...Array(20).keys()].map(i => `HS${i + 1}`)
  .concat([...Array(10).keys()].map(i => `SS${i + 1}`), [...Array(6).keys()].map(i => `EF${i + 1}`))
  .filter(s => !rev[s]);
console.log(missing.length ? `!! skills with no KSEC: ${missing.join(", ")}` : "all 36 skills covered by KSEC");
/* ทักษะเชิงพฤติกรรม (SS) ต้องมีรหัสจริยธรรมหรือลักษณะบุคคลรองรับเสมอ ส่วน HS/EF ใช้ K/S เป็นหลักได้ */
const noEC = Object.entries(rev).filter(([s, r]) => s.startsWith("SS") && !r.E.length && !r.C.length).map(([s]) => s);
console.log(noEC.length ? `!! soft skills with no E/C: ${noEC.join(", ")}` : "every soft skill has an ethics or character code");

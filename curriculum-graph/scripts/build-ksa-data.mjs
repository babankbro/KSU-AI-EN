/* Generate src/ksaData.js from the vault codebook so the app can never drift from the document.
   Source: Labor_Growth_Report_Vault/05_TQF2_Academic_Drafts/18_KSA_Codebook.md
   Run:    npm run build:ksa                                                            */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const SRC = path.join(root, "Labor_Growth_Report_Vault/05_TQF2_Academic_Drafts/18_KSA_Codebook.md");
const OUT = path.join(root, "curriculum-graph/src/ksaData.js");

const md = fs.readFileSync(SRC, "utf8");
const between = (a, b) => md.split(a)[1].split(b)[0];

const CODE = /\b(?:HS|SS|EF)\d{1,2}\b/g;
function expand(text) {
  const out = new Set(text.match(CODE) || []);
  for (const m of text.matchAll(/\b(HS|SS|EF)(\d{1,2})\s*[–-]\s*(?:HS|SS|EF)?(\d{1,2})\b/g))
    for (let i = +m[2]; i <= +m[3]; i++) out.add(m[1] + i);
  return [...out];
}
const aiskOf = t => [...new Set(t.match(/AISK\d{2}/g) || [])];
const ploOf = t => [...new Set([...t.matchAll(/PLO(\d)/g)].map(m => +m[1]))].sort();

const K = [], S = [], A = [];

/* ── Knowledge: | **K1** | name | scope | skills | AISK | PLO | ── */
for (const m of between("# ส่วน 1", "# ส่วน 2").matchAll(/^\|\s*\*\*(K\d+)\*\*\s*\|(.+)\|\s*$/gm)) {
  const c = m[2].split("|").map(x => x.trim());
  K.push({ id: m[1], name: c[0], scope: c[1] || "", skills: expand(c[2] || ""), aisk: aiskOf(c[3] || ""), plo: ploOf(c[4] || "") });
}

/* ── Skill: callout cards with a "ทำอะไรได้บ้าง" bullet list ── */
for (const card of between("# ส่วน 2", "# ส่วน 3").split(/^> \[!abstract\]- /m).slice(1)) {
  const head = card.split("\n")[0];
  const h = head.match(/\*\*(S\d+)\s*·\s*(.+?)\*\*\s*—\s*(.+)/);
  if (!h) continue;
  const metaLine = card.split("\n").find(l => l.startsWith("> **🔗 AISK**")) || "";
  S.push({
    id: h[1], name: h[2].trim(),
    can: card.split("\n").filter(l => /^>\s*-\s/.test(l)).map(l => l.replace(/^>\s*-\s*/, "").trim()),
    skills: expand(h[3]),
    type: /Soft/.test(h[3]) ? "Soft" : /ฐานวิศวกรรม/.test(h[3]) ? "ฐานวิศวกรรม" : "Hard",
    level: (h[3].match(/·\s*(L\d(?:–L\d)?)/) || [, ""])[1],
    aisk: aiskOf(metaLine), plo: ploOf(metaLine)
  });
}

/* ── Attitude: | **A1** | name | covers | skills | PLO | evidence | ── */
for (const m of between("# ส่วน 3", "# ส่วน 4").matchAll(/^\|\s*\*\*(A\d+)\*\*\s*\|(.+)\|\s*$/gm)) {
  const c = m[2].split("|").map(x => x.trim());
  A.push({ id: m[1], name: c[0], covers: c[1] || "", skills: expand(c[2] || ""), plo: ploOf(c[3] || ""), evidence: c[4] || "" });
}

/* ── reverse: skill -> KSA ── */
const rev = {};
for (const r of [...K, ...S, ...A])
  for (const sk of r.skills) (rev[sk] ||= { K: [], S: [], A: [] })[r.id[0]].push(r.id);
const num = a => +a.slice(1);
for (const sk of Object.keys(rev))
  for (const kind of ["K", "S", "A"]) rev[sk][kind] = [...new Set(rev[sk][kind])].sort((a, b) => num(a) - num(b));

if (!K.length || !S.length || !A.length) throw new Error("codebook parse produced an empty set — aborting");

const banner = `/* AUTO-GENERATED by scripts/build-ksa-data.mjs — do not edit by hand.
   Source of truth: Labor_Growth_Report_Vault/05_TQF2_Academic_Drafts/18_KSA_Codebook.md
   Regenerate with: npm run build:ksa
   K${K.length} · S${S.length} · A${A.length} */\n\n`;
fs.writeFileSync(OUT,
  banner +
  `export const KNOWLEDGE = ${JSON.stringify(K, null, 1)};\n\n` +
  `export const SKILLS_KSA = ${JSON.stringify(S, null, 1)};\n\n` +
  `export const ATTITUDES = ${JSON.stringify(A, null, 1)};\n\n` +
  `export const SKILL_TO_KSA = ${JSON.stringify(rev, null, 1)};\n\n` +
  `export const KSA_BY_ID = Object.fromEntries([...KNOWLEDGE, ...SKILLS_KSA, ...ATTITUDES].map(r => [r.id, r]));\n`,
  "utf8");

console.log(`ksaData.js: K=${K.length} S=${S.length} A=${A.length} · skills mapped=${Object.keys(rev).length}`);
const missing = [...Array(20).keys()].map(i => `HS${i + 1}`)
  .concat([...Array(10).keys()].map(i => `SS${i + 1}`), [...Array(6).keys()].map(i => `EF${i + 1}`))
  .filter(s => !rev[s]);
console.log(missing.length ? `!! skills with no KSA: ${missing.join(", ")}` : "all 36 skills covered by KSA");

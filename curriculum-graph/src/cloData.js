const orderOf = code => {
  const c = COURSES.find(x => x.c === code);
  return c && c.sem ? c.sem : 99;
};

/** รายวิชาที่มี CLO เรียงตามภาคการศึกษาตามแผนการเรียนใน data.js */
export const CLO_LIST = CLO_COURSES
  .map(x => {
    const c = COURSES.find(o => o.c === x.c);
    return { ...x, course: c, sem: orderOf(x.c), y: c ? c.y : 0, g: c ? c.g : "ge" };
  })
  .sort((a, b) => a.sem - b.sem || a.c.localeCompare(b.c));

export const cloOf = code => CLO_LIST.find(x => x.c === code) || null;

/** ระดับสูงสุด (I<R<M) ที่รายวิชารับผิดชอบในแต่ละ PLO — ใช้ทำ Curriculum Mapping 4.6 */
export function ploLevels(entry) {
  const out = {};
  entry.clos.forEach(clo => clo.plo.forEach(([n, lv]) => {
    if (!out[n] || LEVEL_ORDER[lv] > LEVEL_ORDER[out[n]]) out[n] = lv;
  }));
  return out;
}

/** สรุปราย PLO: รายวิชาที่มี CLO รับผิดชอบ + ระดับสูงสุด — ใช้ทำตารางสรุป 4.7 */
export const PLO_ROLLUP = [1, 2, 3, 4, 5, 6, 7].map(n => {
  const rows = CLO_LIST
    .map(e => {
      const hits = e.clos.filter(c => c.plo.some(([p]) => p === n));
      if (!hits.length) return null;
      const lv = hits.flatMap(c => c.plo.filter(([p]) => p === n).map(([, l]) => l))
        .reduce((a, b) => (LEVEL_ORDER[b] > LEVEL_ORDER[a] ? b : a), "I");
      return { c: e.c, clos: hits.map(h => h.n), lv, ylo: [...new Set(hits.flatMap(h => h.ylo))] };
    })
    .filter(Boolean);
  const top = rows.reduce((a, r) => (LEVEL_ORDER[r.lv] > LEVEL_ORDER[a] ? r.lv : a), "I");
  return { plo: n, rows, top, cloCount: rows.reduce((s, r) => s + r.clos.length, 0) };
});

